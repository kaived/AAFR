"""Recorded research tournaments as a C++ test fixture.

Reads results/{congestion,loss}/tournaments.jsonl of the research engine
(https://github.com/oddproblem/Adaptive-runtime, commit 6b6c008) from a local
checkout given with --source, and writes
tests/fixtures/research/recorded_tournaments.h: for every tournament, each
arm's recorded per-frame log10 RTT, probes sent / received, mean RTT, path
bandwidth and goodness, and the engine's recorded statistics and decision.
The values are copied, not recomputed. They are an independent reference for
the statistics layer: AAFR must reproduce the recorded outputs from the
recorded frame values.

  python -I tests/research/recorded_tournaments.py --source <checkout>
  python -I tests/research/recorded_tournaments.py --source <checkout> --check
"""

import argparse
import hashlib
import json
import math
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "tests" / "fixtures" / "research" / "recorded_tournaments.h"
FILES = ["results/congestion/tournaments.jsonl", "results/loss/tournaments.jsonl"]
COMMIT = "6b6c008fc484bcbadfb8d8447acf36fe5f39e10d"


def lit(x):
    if x is None:
        return "kMissing"
    if isinstance(x, bool):
        return "true" if x else "false"
    x = float(x)
    return "kMissing" if not math.isfinite(x) else repr(x)


def blob(source, path):
    # The committed bytes (independent of any line-ending conversion).
    return subprocess.run(["git", "-C", str(source), "cat-file", "-p", f"{COMMIT}:{path}"],
                          check=True, capture_output=True).stdout


def path_lit(p):
    return "{" + ", ".join(f'"{n}"' for n in p) + "}"


def build(source):
    out = ["#pragma once", "",
           "// GENERATED by tests/research/recorded_tournaments.py -- do not edit by hand.",
           f"// Source: https://github.com/oddproblem/Adaptive-runtime commit {COMMIT}."]
    records = []
    for rel in FILES:
        data = blob(source, rel)
        out.append(f"//   {rel} sha256 {hashlib.sha256(data).hexdigest()}")
        run = rel.split("/")[1]
        for line in data.decode("utf-8").splitlines():
            if line.strip():
                records.append((run, json.loads(line)))
    out += ["// Recorded outputs of the research engine; values copied, not recomputed.",
            "// The files were added in commit a0ce0ed and are unchanged at the source commit.",
            "// The source repository declares no license: redistribution permission is",
            "// NOT ESTABLISHED and must be obtained from its owner.", "",
            "#include <limits>", "#include <string>", "#include <vector>", "",
            "namespace aafr::recorded_tournaments {", "",
            "inline constexpr double kMissing = std::numeric_limits<double>::quiet_NaN();", "",
            "struct Arm {", "  const char* label;", "  bool incumbent;", "  std::vector<std::string> path;",
            "  int sent;", "  int recv;", "  double mean_rtt_ms;", "  double bottleneck_bw_mbps;",
            "  double goodness;", "  std::vector<double> frame_log10_rtt;  // kMissing for a frame without valid blocks", "};", "",
            "struct Test {", "  const char* challenger;", "  double f;", "  double df2;", "  double p;", "  double p_holm;",
            "  double eta2_partial;", "  double mean_diff_log10;", "  double ci_low_log10;", "  double ci_high_log10;",
            "  double rtt_ratio;", "  double delta_goodness;", "  double s_eta;", "  double s_ci;", "  double s_g;",
            "  double c;", "  const char* constraint;", "  bool significant;", "  bool passes;", "};", "",
            "struct Tournament {", "  const char* run;", "  int id;", "  double t_s;", "  std::vector<Arm> arms;",
            "  std::vector<Test> tests;", "  bool swap;", "};", "",
            "inline const std::vector<Tournament> kTournaments = {"]
    for run, d in records:
        out.append(f'  {{"{run}", {d["id"]}, {lit(d["t"])}, {{')
        for a in d["arms"]:
            frames = ", ".join(lit(v) for v in a["frame_log10_rtt"])
            out.append(f'    {{"{a["label"]}", {lit(a["incumbent"])}, {path_lit(a["path"])}, {a["sent"]}, {a["recv"]}, '
                       f'{lit(a["mean_rtt_ms"])}, {lit(a["bottleneck_bw_mbps"])}, {lit(a["goodness"])}, {{{frames}}}}},')
        out.append("  }, {")
        for t in d["tests"]:
            c = t["confidence"]
            out.append(f'    {{"{t["challenger"]}", {lit(t["F"])}, {lit(t["df2"])}, {lit(t["p"])}, {lit(t["p_holm"])}, '
                       f'{lit(t["eta2_partial"])}, {lit(t["mean_diff_log10"])}, {lit(t["ci_log10"][0])}, {lit(t["ci_log10"][1])}, '
                       f'{lit(t["rtt_ratio"])}, {lit(t["delta_goodness"])}, {lit(c["s_eta"])}, {lit(c["s_ci"])}, '
                       f'{lit(c["s_g"])}, {lit(c["C"])}, "{c.get("constraint", "")}", {lit(c["significant"])}, {lit(c["passes"])}}},')
        out.append(f'  }}, {lit(d.get("swap") is not None)}}},')  # "swap" is absent when the engine kept the path.
    out += ["};", "", "}  // namespace aafr::recorded_tournaments", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", required=True, help="local checkout of oddproblem/Adaptive-runtime")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build(pathlib.Path(args.source))
    if args.check:
        same = OUTPUT.exists() and OUTPUT.read_text(encoding="utf-8") == text
        print("recorded_tournaments.h is " + ("up to date" if same else "stale"))
        return 0 if same else 1
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
