#pragma once

// V0.7.3 HTTP/1.1 proxy message handling for the browser forwarding gateway.
// Plain C++17, no I/O: parsing, validation and re-serialisation only, so
// every rule is unit-testable.
//
// Request side (from the browser): the request head must be complete,
// CRLF-delimited, within the reader's size limit and unambiguous. CONNECT
// takes an authority-form target; every other method an absolute-form
// http:// target. Rejected outright: bare CR or LF, obsolete line folding,
// whitespace before a header colon, control characters, several Host
// headers, conflicting or non-numeric Content-Length, Content-Length
// together with Transfer-Encoding (the classic smuggling ambiguity), any
// request Transfer-Encoding (chunked uploads are not supported), userinfo
// or fragments in the target, origin-form requests addressed to the gateway
// itself, https:// absolute-form targets (browsers use CONNECT) and TRACE.
//
// The forwarded request is rebuilt in origin-form with the hop-by-hop
// headers removed (Connection and every header it names, Proxy-Connection,
// Keep-Alive, Proxy-Authorization, TE, Trailer, Upgrade), Host set from the
// target, and "Connection: close", so exactly one request travels per
// upstream connection. Other headers pass unchanged and are never logged.
//
// Response side (plain HTTP only; CONNECT tunnels are opaque): the response
// head is parsed to find where the body ends (none, Content-Length, chunked
// or until close) and re-sent with "Connection: close"; body bytes pass
// unchanged.

#include <cstdint>
#include <optional>
#include <string>
#include <vector>

namespace aafr::gateway {

struct HeaderField {
  std::string name;
  std::string value;
};

enum class ProxyRequestKind { Connect, Forward };

struct ProxyRequest {
  ProxyRequestKind kind{ProxyRequestKind::Forward};
  std::string method;
  std::string version;  // HTTP/1.1 or HTTP/1.0
  std::string target_host;
  std::uint16_t target_port{0};
  std::string origin_form;  // Path and query (Forward only).
  std::vector<HeaderField> headers;
  std::optional<std::uint64_t> content_length;
};

struct ParseOutcome {
  bool ok{false};
  int status{400};      // HTTP status to answer with when !ok.
  std::string reason;   // Short code, e.g. "obs_fold", "smuggling_ambiguity".
};

inline constexpr std::size_t kMaxHeaderFields = 100;

// `head` is everything up to and including the first CRLFCRLF.
ParseOutcome ParseProxyRequestHead(const std::string& head, ProxyRequest* out);
std::string BuildOriginRequestHead(const ProxyRequest& request);

struct ResponseHead {
  std::string version;
  int status{0};
  std::string reason_phrase;
  std::vector<HeaderField> headers;
};

bool ParseResponseHead(const std::string& head, ResponseHead* out, std::string* reason);
// The head re-sent to the browser: hop-by-hop headers removed, "Connection:
// close" added.
std::string BuildClientResponseHead(const ResponseHead& head);

enum class BodyFraming { None, ContentLength, Chunked, UntilClose, Invalid };
const char* ToString(BodyFraming value);
BodyFraming ResponseFraming(const ResponseHead& head, const std::string& request_method, std::uint64_t* length);

// Follows a chunked body to its end without changing it.
class ChunkedTracker {
 public:
  // Consumes bytes up to the end of the body; returns how many of `size`
  // belong to it (all of them until Done).
  std::size_t Feed(const char* data, std::size_t size);
  bool done() const { return state_ == State::Done; }
  bool failed() const { return state_ == State::Error; }

 private:
  enum class State { Size, Extension, SizeLf, Data, DataCr, DataLf, TrailerStart, Trailer, TrailerLf, FinalLf, Done, Error };
  State state_{State::Size};
  std::uint64_t remaining_{0};
  int size_digits_{0};
  std::size_t line_bytes_{0};
};

// A minimal error response generated by the gateway itself. The body names
// the AAFR reason code; nothing from the request is echoed.
std::string GatewayErrorResponse(int status, const std::string& reason_code);
const char* StatusText(int status);

// Case-insensitive ASCII comparison.
bool EqualsIgnoreCase(const std::string& a, const std::string& b);

}  // namespace aafr::gateway
